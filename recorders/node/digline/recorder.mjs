/**
 * What one call consumed, each count a `bigint`. The two cache counts are 0
 * where none was reported; `thinkingTokens` is `null` where none was.
 */
export class Usage {
  constructor(inputTokens, outputTokens, cacheReadTokens = 0n, cacheWriteTokens = 0n, thinkingTokens = null) {
    this.inputTokens = BigInt(inputTokens);
    this.outputTokens = BigInt(outputTokens);
    this.cacheReadTokens = BigInt(cacheReadTokens);
    this.cacheWriteTokens = BigInt(cacheWriteTokens);
    this.thinkingTokens = thinkingTokens === null ? null : BigInt(thinkingTokens);
  }

  asObject() {
    const found = newObject();
    found.input_tokens = this.inputTokens;
    found.output_tokens = this.outputTokens;
    if (this.cacheReadTokens !== 0n) {
      found.cache_read_tokens = this.cacheReadTokens;
    }
    if (this.cacheWriteTokens !== 0n) {
      found.cache_write_tokens = this.cacheWriteTokens;
    }
    if (this.thinkingTokens !== null) {
      found.thinking_tokens = this.thinkingTokens;
    }
    return found;
  }
}

/**
 * One tool call the model asked for. `tool` is `null` where the provider
 * named none; `arguments` is an object, a string, or `null`. A client-side
 * call is `status = "not_reported"` with `resultAbsence = "not_reported"`:
 * the reply ends where the tool would start.
 */
export class ToolCall {
  constructor(tool, args, status, result, resultAbsence) {
    this.tool = tool;
    this.arguments = args;
    this.status = status;
    this.result = result;
    this.resultAbsence = resultAbsence;
  }

  static asked(tool, args) {
    return new ToolCall(tool, args, "not_reported", null, "not_reported");
  }

  asObject() {
    const found = newObject();
    if (this.tool === null) {
      found.tool_absence = "not_reported";
    } else {
      if (this.tool === "") {
        throw new TypeError("a tool call names a tool, or null");
      }
      found.tool = this.tool;
    }
    if (this.arguments !== null && this.arguments !== undefined) {
      found.arguments = typeof this.arguments === "string" ? this.arguments : compact(rounded(this.arguments));
    }
    if (this.result !== null) {
      found.result = this.result;
    }
    if (this.resultAbsence !== null) {
      found.result_absence = this.resultAbsence;
    }
    if (this.status !== "success") {
      found.status = this.status;
    }
    return found;
  }
}

/**
 * One call, as a hook read it: `caseCompartment` and `setup` are JSON values
 * as `parse` reads them, `latencyMs` a number, `toolCalls` a list or `null`
 * where the reply said nothing of tools.
 */
export class Call {
  constructor(caseCompartment, setup, output, latencyMs, usage, finish, toolCalls) {
    this.caseCompartment = caseCompartment;
    this.setup = setup;
    this.output = output;
    this.latencyMs = latencyMs;
    this.usage = usage;
    this.finish = finish;
    this.toolCalls = toolCalls;
  }
}

/** A provider's word for how a reply ended, in digline's vocabulary: digline's `finish_of`. */
export function finishOf(word, table) {
  if (typeof word !== "string" || word === "") {
    return null;
  }
  return Object.hasOwn(table, word) ? table[word] : "other";
}

/**
 * The JSON of each server-sent event in `text`, in order: its `data:` lines
 * joined. OpenAI's closing `[DONE]` is not an event. As `digline record
 * proxy` reads a stream.
 */
export function events(text) {
  const found = [];
  for (const block of text.replaceAll("\r\n", "\n").split("\n\n")) {
    const data = [];
    for (const line of block.split("\n")) {
      if (line.startsWith("data:")) {
        data.push(line.slice("data:".length).replace(/^ +/, ""));
      }
    }
    const joined = data.join("\n");
    if (joined !== "" && joined !== "[DONE]") {
      found.push(parse(joined));
    }
  }
  return found;
}

/** A non-empty string, or `null`. */
export function name(value) {
  return typeof value === "string" && value !== "" ? value : null;
}

/** A whole count, as a `bigint`, or `null`. */
export function count(value) {
  if (typeof value === "bigint") {
    return value;
  }
  if (typeof value === "number" && Number.isFinite(value)) {
    return BigInt(Math.trunc(value));
  }
  return null;
}

/** Python's truth of a JSON value: null, false, 0, "" and empty containers are false. */
export function truthy(value) {
  if (value === null || value === undefined || value === false) {
    return false;
  }
  if (typeof value === "string") {
    return value !== "";
  }
  if (typeof value === "bigint") {
    return value !== 0n;
  }
  if (typeof value === "number") {
    return value !== 0;
  }
  if (Array.isArray(value)) {
    return value.length > 0;
  }
  if (isObject(value)) {
    return Object.keys(value).length > 0;
  }
  return true;
}

/** A shallow copy of a JSON object, or a refusal where `value` is not one. */
export function asObject(value) {
  if (!isObject(value)) {
    throw new TypeError("not a JSON object");
  }
  return Object.assign(newObject(), value);
}

/** A JSON object with the given entries, as `parse` makes one. */
export function object(entries = {}) {
  return Object.assign(newObject(), entries);
}

/** Bytes, a string or nothing, read as UTF-8 text. */
export function textOf(body) {
  if (typeof body === "string") {
    return body;
  }
  if (body instanceof Uint8Array) {
    return Buffer.from(body.buffer, body.byteOffset, body.byteLength).toString("utf8");
  }
  if (body instanceof ArrayBuffer) {
    return Buffer.from(body).toString("utf8");
  }
  return null;
}

/** Milliseconds from a monotonic clock: a duration, never a time. */
export function clock() {
  return performance.now();
}

// ------------------------------------------------------------------ the recorder

/**
 * Records the calls an application makes to a model, as files digline reads:
 * `.digline/<tenant>/recordings/n<pid>-<8 hex>/000001.json` and on. What
 * becomes of them is digline's: `digline record import` lists them and writes
 * the answers a person reviews into a suite's cases.
 *
 *     const recorder = DiglineRecorder.development(root, "acme", "support");
 *     await suite("refunds", () => openai.chat.completions.create(params));
 *
 * The switch is the tenant's `recorder.toml`, the file `digline record on`
 * writes, read with the rules digline's own recorder reads it with, and read
 * again every `interval` seconds. Without a file the recorder is off, a root
 * with no `.digline/` included, unless `DIGLINE_RECORD=1` in development.
 *
 * Two regimes. `development` takes the tenant's name: a switch file that is
 * invalid is said once on standard error and leaves the recorder off.
 * `production` takes a function asked at every call, and refuses to start,
 * with a `StartError`, where a tenant's file is invalid or switches recording
 * on without `redact`, `sample` and `ceiling`, or where `DIGLINE_RECORD=1`.
 *
 * The application's call never fails because of the recorder: what goes wrong
 * is counted, by reason, in `counts()`. This writer keeps no `.counts` file,
 * which is not part of the contract, so `digline record status` says *not
 * counted* for its process.
 */
export class DiglineRecorder {
  #root;
  #app;
  #tenant;
  #tenantFunction;
  #production;
  #writer;
  #switches = new Map();
  #anyOn = false;
  #stamps = new Map();
  #interval = DEFAULT_INTERVAL;
  #nextLook = 0;
  #sizes = new Map();
  #stopped = new Set();
  #commit = undefined;
  #recorded = 0;
  #orphans = 0;
  #notRecorded = new Map();
  #noted = new Map();

  constructor(root, app, tenant, tenantFunction, token) {
    if (token !== CONSTRUCTING) {
      throw new TypeError("use DiglineRecorder.development or DiglineRecorder.production");
    }
    if (typeof app !== "string" || app === "") {
      throw new StartError("DiglineRecorder needs app, a non-empty name");
    }
    this.#root = path.resolve(String(root));
    this.#app = app;
    this.#tenant = tenant;
    this.#tenantFunction = tenantFunction;
    this.#production = tenantFunction !== null;
    if (!WRITERS.has(this.#root)) {
      WRITERS.set(this.#root, new Writer(this.#root));
    }
    this.#writer = WRITERS.get(this.#root);
    if (this.#production && switchedOn()) {
      throw new StartError(
        `${ENVIRONMENT_VARIABLE}=1 with a tenant function, which is production: the variable ` +
          "declares no redaction and no sampling, so in production recording is switched on " +
          "per tenant by its file (digline record on --production) (ADR 0058 §10)",
      );
    }
    this.#readSwitches(true);
    this.#measure();
    this.#nextLook = clock() + this.#interval * 1000;
  }

  /**
   * Development: one tenant, by name. `root` is the directory that holds
   * `.digline/`, usually the repository's root.
   */
  static development(root, tenant, app) {
    if (typeof tenant !== "string" || tenant === "") {
      throw new StartError("DiglineRecorder needs tenant, a non-empty name");
    }
    if (!isName(tenant)) {
      throw new StartError(refusal(tenant));
    }
    if (root === undefined || root === null) {
      throw new TypeError("root");
    }
    return new DiglineRecorder(root, app, tenant, null, CONSTRUCTING);
  }

  /**
   * Production: the tenant is the function's answer at every call, and each
   * tenant's recordings are filed under its own directory.
   */
  static production(root, tenant, app) {
    if (root === undefined || root === null) {
      throw new TypeError("root");
    }
    if (typeof tenant !== "function") {
      throw new TypeError("tenant is a function asked at every call");
    }
    return new DiglineRecorder(root, app, null, tenant, CONSTRUCTING);
  }

  /** The directory that holds `.digline/`. */
  get root() {
    return this.#root;
  }

  /**
   * Whether any tenant records, as of the last look: what a hook asks before
   * it reads a request, so that an off recorder costs one test.
   */
  on() {
    this.#lookIfDue();
    return this.#anyOn;
  }

  /**
   * Records one call the application read itself, its values as JavaScript
   * holds them (read with `fromJs`). Never throws.
   */
  record(call) {
    try {
      const read = new Call(
        fromJs(call.caseCompartment),
        fromJs(call.setup),
        call.output,
        Number(call.latencyMs),
        call.usage ?? null,
        call.finish ?? null,
        call.toolCalls ?? null,
      );
      this.recordAt(read, this.capture());
    } catch (unexpected) {
      this.#count(`unexpected: ${unexpected?.name ?? "Error"}`);
    }
  }

  /**
   * What a hook reads when a call starts: its suite, its episode and, where
   * it names no suite, where it was made. A stream may end in another turn of
   * the event loop, and the call is the scope's that made it.
   */
  capture() {
    const scope = current();
    return { suite: scope.suite, inside: scope.inside, site: scope.suite === null ? this.#callSite() : null };
  }

  /** Records one call made where `at` was captured. Never throws. */
  recordAt(call, at) {
    try {
      this.#lookIfDue();
      if (!this.#anyOn) {
        return;
      }
      const inside = at.inside;
      const late = inside !== null && !OPEN.has(inside) && CLOSED.has(inside);
      const reason = this.#recordCall(call, at.suite, inside, at.site, late);
      if (reason === null && late) {
        this.#note("ended after its episode");
      }
      const seen = reason === null || reason === "writer" ? seenOf(call) : null;
      this.#joined(late ? null : inside, reason, seen);
    } catch (unexpected) {
      this.#count(`unexpected: ${unexpected?.name ?? "Error"}`);
    }
  }

  /**
   * Counts a call a hook could not read, by the stage that failed: what
   * digline's recorder counts as `map`, or `not JSON`.
   */
  /**
   * A reply the hook saw that was not a 2xx: a refusal, 4xx or 5xx, is
   * counted `provider error <status>` and not recorded, there being no reply
   * to record. Any other status passes uncounted. A hook that sees each
   * attempt the SDK makes counts each refused one.
   */
  refused(status, at) {
    if (Number.isInteger(status) && status >= 400 && status <= 599) {
      this.miss(`provider error ${status}`, at);
    }
  }

  miss(reason, at = this.capture()) {
    try {
      this.#lookIfDue();
      if (this.#anyOn) {
        const inside = at.inside;
        const late = inside !== null && !OPEN.has(inside) && CLOSED.has(inside);
        this.#joined(late ? null : inside, reason, null);
      }
    } catch (unexpected) {
      this.#count(`unexpected: ${unexpected?.name ?? "Error"}`);
    }
  }

  /**
   * `recorded`, `not_recorded` by reason, `orphan` and `noted`, as of now, in
   * memory, as digline's `digline_counts`.
   */
  counts() {
    const sorted = (counted) =>
      Object.fromEntries([...counted.entries()].sort(([a], [b]) => byCodePoint(a, b)));
    return {
      noted: sorted(this.#noted),
      not_recorded: sorted(this.#notRecorded),
      orphan: this.#orphans,
      recorded: this.#recorded,
    };
  }

  #count(reason) {
    if (reason === null) {
      this.#recorded++;
    } else {
      this.#notRecorded.set(reason, (this.#notRecorded.get(reason) ?? 0) + 1);
    }
  }

  #note(what) {
    this.#noted.set(what, (this.#noted.get(what) ?? 0) + 1);
  }

  #joined(inside, reason, seen) {
    this.#count(reason);
    if (inside === null) {
      if (reason === null && OPEN.size > 0) {
        this.#orphans++;
      }
      return;
    }
    OPEN.get(inside)?.add(seen);
  }

  /** The reason a call was not recorded, or `null` where it was; never throws. */
  #recordCall(call, suiteName, inside, site, late) {
    let stage = "tenant";
    try {
      const tenantNow = this.#tenantNow();
      if (tenantNow === null) {
        return stage;
      }
      const on = this.#switches.get(tenantNow);
      if (!on?.on) {
        return "off for this tenant";
      }
      const collector = inside === null ? undefined : OPEN.get(inside);
      if (collector !== undefined) {
        if (collector.sampledOut) {
          return "sampled out";
        }
      } else if (!sampledIn(on)) {
        return "sampled out";
      }
      if (this.#atCeiling(tenantNow, on)) {
        return "ceiling";
      }
      stage = "map";
      if (call.caseCompartment === null || call.setup === null || typeof call.output !== "string") {
        return stage;
      }
      stage = "not JSON";
      const document = singleDocument(tenantNow, this.#app, suiteName, call, now());
      if (inside !== null) {
        document.episode = inside;
      }
      if (site !== null) {
        document.call_site = site;
      }
      if (late || (inside === null && OPEN.size > 0)) {
        document.orphan = true;
      }
      this.#markGate(document, tenantNow);
      stage = "writer";
      this.#write(tenantNow, document);
    } catch {
      return stage;
    }
    if (call.usage === null) {
      this.#note("usage not reported");
    }
    return null;
  }

  #markGate(document, tenantNow) {
    const found = gate(this.#root, tenantNow, Date.now());
    if (found !== null) {
      document.origin = found[0];
      if (found[1] !== null) {
        document.run_id = found[1];
      }
    }
  }

  #write(tenantNow, document) {
    const grown = this.#writer.write(tenantNow, file(document) + "\n");
    this.#sizes.set(tenantNow, (this.#sizes.get(tenantNow) ?? 0n) + BigInt(grown));
  }

  #tenantNow() {
    const found = this.#production ? this.#tenantFunction() : this.#tenant;
    // A function's answer that is not a name is no tenant: it never becomes
    // a directory, and the call is counted `tenant`.
    return isName(found) ? found : null;
  }

  #atCeiling(tenantNow, on) {
    if (this.#stopped.has(tenantNow)) {
      return true;
    }
    const size = this.#sizes.get(tenantNow) ?? 0n;
    if (size < on.ceiling) {
      return false;
    }
    this.#stopped.add(tenantNow);
    this.#markCeiling(tenantNow, on.ceiling, size);
    return true;
  }

  #markCeiling(tenantNow, ceiling, size) {
    const directory = path.join(this.#root, STORE, tenantNow, RECORDINGS);
    try {
      fs.mkdirSync(directory, { recursive: true });
      const temporary = path.join(directory, `.${CEILING_MARKER}.${process.pid}`);
      fs.writeFileSync(temporary, `{"ceiling": ${ceiling}, "size": ${size}}\n`, "utf8");
      fs.renameSync(temporary, path.join(directory, CEILING_MARKER));
    } catch {
      // A marker that cannot be written is not an error the application hears of.
    }
  }

  /**
   * The file and function that made the call: the first frame outside these
   * files and outside `node_modules`, where the SDKs and the libraries built
   * on them live. The file is said relative to the root. A function that
   * returns an SDK's promise without awaiting it is not on the stack when
   * the call is made, and the frame that awaited it is named instead.
   */
  #callSite() {
    const limit = Error.stackTraceLimit;
    const prepare = Error.prepareStackTrace;
    try {
      Error.stackTraceLimit = 50;
      Error.prepareStackTrace = (_, frames) => frames;
      const holder = {};
      Error.captureStackTrace(holder);
      for (const frame of holder.stack) {
        let where = frame.getFileName();
        if (!where || where.startsWith("node:")) {
          continue;
        }
        if (where.startsWith("file://")) {
          where = fileURLToPath(where);
        }
        if (where.split(path.sep).includes("node_modules") || path.dirname(where) === HERE) {
          continue;
        }
        const relative = path.relative(this.#root, where).split(path.sep).join("/");
        return `${relative}:${frame.getFunctionName() ?? "<anonymous>"}`;
      }
      return null;
    } catch {
      return null;
    } finally {
      Error.stackTraceLimit = limit;
      Error.prepareStackTrace = prepare;
    }
  }

  // ---------------------------------------------------------------- the episode

  /**
   * One turn of an agent, recorded as one recording with the calls made
   * inside it, written when `turn` ends. `suiteName` may be `null`;
   * `caseCompartment` is the input that started the turn, and its JSON text
   * is the answer's `input`. `turn` is given the episode and may be
   * asynchronous: what it returns is returned, and a turn that throws is
   * recorded `interrupted` and the error passed on. `options.setup` gives the
   * episode's setup rather than deriving it from its calls.
   */
  episode(suiteName, caseCompartment, turn, options = {}) {
    const episode = new Episode(this, suiteName, caseCompartment, options.setup ?? null);
    const run = () => turn(episode);
    let result;
    try {
      result = episode.id === null ? run() : SCOPE.run({ ...current(), inside: episode.id }, run);
    } catch (failed) {
      episode.interrupted();
      episode.close();
      throw failed;
    }
    if (result !== null && typeof result === "object" && typeof result.then === "function") {
      return result.then(
        (value) => {
          episode.close();
          return value;
        },
        (failed) => {
          episode.interrupted();
          episode.close();
          throw failed;
        },
      );
    }
    episode.close();
    return result;
  }

  episodeSampledIn() {
    try {
      const tenantNow = this.#tenantNow();
      const on = tenantNow === null ? undefined : this.#switches.get(tenantNow);
      return !on?.on || sampledIn(on);
    } catch {
      return true;
    }
  }

  get anyOn() {
    return this.#anyOn;
  }

  siteForEpisode() {
    return this.#callSite();
  }

  closeEpisode(episode, elapsedMs) {
    let reason;
    try {
      reason = this.#recordEpisode(episode, elapsedMs);
    } catch (unexpected) {
      reason = `unexpected: ${unexpected?.name ?? "Error"}`;
    }
    this.#count(reason);
  }

  countSampledOut() {
    this.#count("sampled out");
  }

  #recordEpisode(episode, elapsedMs) {
    let stage = "setup";
    try {
      const calls = episode.collector.calls();
      let setup;
      if (episode.setup !== null) {
        setup = episode.setup;
      } else {
        setup = newObject();
        setup.child_setups = [...episode.collector.digests()];
        const found = this.#gitCommit();
        if (found !== null) {
          setup.git_commit = found;
        }
      }
      stage = "not JSON";
      setup = compartment(setup);
      const caseCompartment = compartment(episode.caseCompartment);
      const digest = setupDigest(setup);
      episode.collector.digest = digest;
      const question = compact(caseCompartment);

      stage = "output";
      let text;
      let kind;
      if (episode.outputGiven) {
        if (typeof episode.answer === "string") {
          text = episode.answer;
          kind = "text";
        } else if (isObject(episode.answer)) {
          text = compact(rounded(episode.answer));
          kind = "structured";
        } else {
          return stage;
        }
      } else if (calls.length > 0) {
        text = calls[calls.length - 1].text;
        kind = "text";
      } else {
        return "no output";
      }

      const made = [];
      let known = true;
      const trajectory = [];
      for (const seen of calls) {
        made.push({ finish: seen.finish, toolCalls: seen.calls });
        if (seen.calls === null) {
          known = false;
        } else {
          trajectory.push(...seen.calls);
        }
      }
      const steps = stepsOf(made);
      let trajectoryChars = 0;
      for (const each of known ? trajectory : []) {
        const written = each.asObject();
        trajectoryChars += chars(written.tool) + chars(written.arguments) + chars(written.result);
      }
      const response = newObject();
      if (chars(text) > MAX_RECORDED_CHARS || chars(question) > MAX_RECORDED_CHARS || trajectoryChars > MAX_RECORDED_CHARS) {
        response.oversize = true;
        response.latency_ms = round(elapsedMs);
      } else {
        response.output = text;
        response.kind = kind;
        response.input = question;
        response.latency_ms = round(elapsedMs);
        if (known) {
          response.tool_calls = trajectory.map((each) => each.asObject());
          response.tools = trajectory.map((each) => each.tool);
        }
        if (steps.length > 0) {
          response.steps = steps;
        }
        const finish = made.length === 0 ? null : made[made.length - 1].finish;
        if (finish !== null) {
          response.finish = finish;
        }
      }

      stage = "tenant";
      const tenantNow = this.#tenantNow();
      if (tenantNow === null) {
        return stage;
      }
      const on = this.#switches.get(tenantNow);
      if (!on?.on) {
        return "off for this tenant";
      }
      if (this.#atCeiling(tenantNow, on)) {
        return "ceiling";
      }

      stage = "not JSON";
      const document = makeDocument(tenantNow, this.#app, episode.suite, caseCompartment, setup, digest, response, now());
      this.#markGate(document, tenantNow);
      document.id = episode.id;
      if (episode.parent !== null) {
        document.episode = episode.parent;
      }
      if (episode.site !== null) {
        document.call_site = episode.site;
      }
      if (episode.wasInterrupted) {
        document.interrupted = true;
      }
      const unrecorded = episode.collector.childrenUnrecorded();
      if (unrecorded > 0) {
        document.unrecorded_children = BigInt(unrecorded);
      }
      stage = "writer";
      this.#write(tenantNow, document);
    } catch {
      return stage;
    }
    return null;
  }

  /** The repository's commit, as digline reads it for a run, cached until the next look. */
  #gitCommit() {
    if (this.#commit === undefined) {
      const sha = this.#git("rev-parse", "HEAD");
      let found = null;
      if (sha !== null) {
        const status = this.#git("status", "--porcelain");
        found = status !== null && status !== "" ? `${sha}-dirty` : sha;
      }
      this.#commit = found;
    }
    return this.#commit;
  }

  #git(...args) {
    try {
      return execFileSync("git", ["-C", this.#root, ...args], {
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
        timeout: 10_000,
      }).trim();
    } catch {
      return null;
    }
  }

  // ---------------------------------------------------------------- the switch, read

  #switchFiles() {
    const store = path.join(this.#root, STORE);
    if (!this.#production) {
      return new Map([[this.#tenant, path.join(store, this.#tenant, SWITCH_FILE)]]);
    }
    const found = new Map();
    try {
      for (const entry of fs.readdirSync(store, { withFileTypes: true })) {
        const candidate = path.join(store, entry.name, SWITCH_FILE);
        if (fs.statSync(path.join(store, entry.name)).isDirectory() && isFile(candidate)) {
          found.set(entry.name, candidate);
        }
      }
    } catch {
      // No .digline/ yet: no tenant has a switch.
    }
    return found;
  }

  #readSwitches(starting) {
    const read = new Map();
    const seen = new Map();
    const before = this.#stamps;
    for (const [tenantName, where] of this.#switchFiles()) {
      const stamped = stamp(where);
      if (stamped === null) {
        continue;
      }
      seen.set(tenantName, stamped);
      try {
        let text;
        try {
          text = fs.readFileSync(where, "utf8");
        } catch {
          throw new StartError(`${where} cannot be read`);
        }
        const found = parseSwitch(text, where, this.#production);
        if (this.#production && found.on && !writable(path.dirname(where))) {
          throw new StartError(
            `${where} switches recording on in production, and ${path.dirname(where)} is not a ` +
              "writable directory to put the recordings in (ADR 0058 §10)",
          );
        }
        read.set(tenantName, found);
      } catch (invalid) {
        if (!(invalid instanceof StartError)) {
          throw invalid;
        }
        if (starting && this.#production) {
          throw invalid;
        }
        this.#count("config invalid");
        if (stamped !== before.get(tenantName)) {
          process.stderr.write(`digline recorder: not recording for this tenant: ${invalid.message}\n`);
        }
      }
    }
    if (!this.#production && seen.size === 0 && switchedOn()) {
      read.set(this.#tenant, {
        on: true,
        sample: DEFAULT_SAMPLE,
        redact: "none",
        ceiling: DEFAULT_CEILING,
        interval: DEFAULT_INTERVAL,
        production: false,
        declared: new Set(),
      });
    }
    this.#stamps = seen;
    this.#switches = read;
    this.#anyOn = [...read.values()].some((each) => each.on);
    this.#interval = read.size === 0 ? DEFAULT_INTERVAL : Math.min(...[...read.values()].map((each) => each.interval));
  }

  #lookIfDue() {
    if (clock() < this.#nextLook) {
      return;
    }
    try {
      const now = new Map();
      for (const [tenantName, where] of this.#switchFiles()) {
        const found = stamp(where);
        if (found !== null) {
          now.set(tenantName, found);
        }
      }
      const same =
        now.size === this.#stamps.size && [...now].every(([key, value]) => this.#stamps.get(key) === value);
      if (!same) {
        this.#readSwitches(false);
      }
      this.#measure();
      this.#commit = undefined;
    } catch {
      this.#count("config invalid");
    } finally {
      this.#nextLook = clock() + this.#interval * 1000;
    }
  }

  /** Each recording tenant's size, from the disk; a stopped tenant under its ceiling resumes. */
  #measure() {
    for (const [tenantName, on] of this.#switches) {
      if (!on.on) {
        continue;
      }
      const size = recordingsSize(path.join(this.#root, STORE, tenantName, RECORDINGS));
      this.#sizes.set(tenantName, size);
      if (this.#stopped.has(tenantName) && size < on.ceiling) {
        this.#stopped.delete(tenantName);
        try {
          fs.rmSync(path.join(this.#root, STORE, tenantName, RECORDINGS, CEILING_MARKER), { force: true });
        } catch {
          // The status reads a stale marker until the next look removes it.
        }
      }
    }
  }
}

const CONSTRUCTING = Symbol("DiglineRecorder");

function sampledIn(on) {
  return on.sample >= 1 || Math.random() < on.sample;
}

function stamp(where) {
  try {
    const seen = fs.statSync(where, { bigint: true });
    return `${seen.mtimeNs}:${seen.size}`;
  } catch {
    return null;
  }
}

function isFile(where) {
  try {
    return fs.statSync(where).isFile();
  } catch {
    return false;
  }
}

function writable(directory) {
  for (let candidate = directory; ; candidate = path.dirname(candidate)) {
    if (fs.existsSync(candidate)) {
      try {
        fs.accessSync(candidate, fs.constants.W_OK | fs.constants.X_OK);
        return fs.statSync(candidate).isDirectory();
      } catch {
        return false;
      }
    }
    if (path.dirname(candidate) === candidate) {
      return false;
    }
  }
}

function recordingsSize(directory) {
  let total = 0n;
  try {
    for (const folder of fs.readdirSync(directory, { withFileTypes: true })) {
      if (!folder.isDirectory()) {
        continue;
      }
      for (const item of fs.readdirSync(path.join(directory, folder.name), { withFileTypes: true })) {
        if (item.name.endsWith(".json") && !item.name.startsWith(".")) {
          total += BigInt(fs.lstatSync(path.join(directory, folder.name, item.name)).size);
        }
      }
    }
  } catch {
    return total;
  }
  return total;
}

function chars(text) {
  return typeof text === "string" ? [...text].length : 0;
}

/** A compartment as JSON carries it: checked, and copied, so what is written was checked. */
function compartment(given) {
  return parse(compact(given));
}

/** What a call adds to its episode, or `null` where it cannot be read. */
function seenOf(call) {
  try {
    return {
      digest: setupDigest(call.setup),
      text: call.output,
      finish: call.finish,
      calls: call.toolCalls === null ? null : [...call.toolCalls],
    };
  } catch {
    return null;
  }
}

/**
 * The steps of a trajectory, as digline's `steps_of` makes them: one `model`
 * step per call, with its finish, then one `tool` step per tool call it asked
 * for, indexed from 0.
 */
export function stepsOf(calls) {
  const steps = [];
  for (const call of calls) {
    const model = newObject();
    model.index = BigInt(steps.length);
    model.actor = "model";
    if (call.finish !== null && call.finish !== undefined) {
      model.finish = call.finish;
    }
    steps.push(model);
    for (const each of call.toolCalls ?? []) {
      const tool = each.asObject();
      tool.index = BigInt(steps.length);
      tool.actor = "tool";
      steps.push(tool);
    }
  }
  return steps;
}

/**
 * A single call's recording, before what only the moment of writing knows:
 * its episode, its call site, whether it is an orphan.
 */
export function singleDocument(tenant, app, suiteName, call, recordedAt) {
  const caseCompartment = compartment(call.caseCompartment);
  const setup = compartment(call.setup);
  return makeDocument(
    tenant,
    app,
    suiteName,
    caseCompartment,
    setup,
    setupDigest(setup),
    singleResponse(call, caseCompartment),
    recordedAt,
  );
}

/** A single call's response, as `recorded()` builds it in digline. */
function singleResponse(call, caseCompartment) {
  const messages = caseCompartment.messages;
  const question = messages === undefined || messages === null ? null : compact(messages);
  let calls = null;
  let tools = null;
  let steps = null;
  if (call.toolCalls !== null) {
    calls = call.toolCalls.map((each) => each.asObject());
    tools = call.toolCalls.map((each) => each.tool);
    steps = stepsOf([{ finish: call.finish, toolCalls: call.toolCalls }]);
  }
  let trajectory = 0;
  for (const each of calls ?? []) {
    trajectory += chars(each.tool) + chars(each.arguments) + chars(each.result);
  }
  for (const toolName of tools ?? []) {
    trajectory += chars(toolName);
  }
  const response = newObject();
  if (chars(call.output) > MAX_RECORDED_CHARS || chars(question) > MAX_RECORDED_CHARS || trajectory > MAX_RECORDED_CHARS) {
    response.oversize = true;
    response.latency_ms = round(call.latencyMs);
    if (call.usage !== null) {
      response.usage = call.usage.asObject();
    }
    return response;
  }
  response.output = call.output;
  response.kind = "text";
  if (question !== null) {
    response.input = question;
  }
  response.latency_ms = round(call.latencyMs);
  if (call.usage !== null) {
    response.usage = call.usage.asObject();
  }
  if (calls !== null) {
    response.tool_calls = calls;
    response.tools = tools;
  }
  if (call.finish !== null) {
    response.finish = call.finish;
  }
  if (steps !== null) {
    response.steps = steps;
  }
  return response;
}

function makeDocument(tenantNow, app, suiteName, caseCompartment, setup, digest, response, recordedAt) {
  const document = newObject();
  document.recording_version = BigInt(RECORDING_VERSION);
  document.source_tenant = tenantNow;
  document.app = app;
  document.suite = suiteName ? suiteName : UNASSIGNED;
  document.case = caseCompartment;
  document.setup = setup;
  document.setup_digest = digest;
  document.response = response;
  document.recorded_at = recordedAt;
  return document;
}

/**
 * What `digline.host.gate` reads: the markers in `.digline/<tenant>/runs/.gate/`,
 * a file whose name starts with a dot or does not end in `.json` left out,
 * live where it was touched in the last 120 seconds. `null` where none is
 * live; else `"gate"` and the run's key, the key `null` where more than one
 * is live or the one live marker cannot be read. A listing that fails is
 * none: the application's call never fails because of this.
 */
export function gate(root, tenant, nowMillis) {
  let place = path.join(root, STORE, tenant, ...GATE_DIRECTORY);
  try {
    // Held inside the store, as digline holds it: a .gate that is a link out
    // of .digline/, or a marker that links out of .gate, is not read.
    const real = fs.realpathSync(place);
    if (!inside(real, fs.realpathSync(path.join(root, STORE)))) {
      return null;
    }
    place = real;
  } catch {
    return null;
  }
  const live = [];
  try {
    for (const entry of fs.readdirSync(place)) {
      if (entry.startsWith(".") || !entry.endsWith(".json")) {
        continue;
      }
      const marker = path.join(place, entry);
      let age;
      try {
        if (!inside(fs.realpathSync(marker), place)) {
          continue;
        }
        age = (nowMillis - fs.statSync(marker).mtimeMs) / 1000;
      } catch {
        continue;
      }
      if (age <= STALE_SECONDS) {
        live.push(runIdOf(marker));
      }
    }
  } catch {
    return null;
  }
  if (live.length === 0) {
    return null;
  }
  return [GATE_ORIGIN, live.length === 1 ? live[0] : null];
}

function inside(candidate, directory) {
  return candidate === directory || candidate.startsWith(directory + path.sep);
}

function runIdOf(marker) {
  try {
    const document = parse(fs.readFileSync(marker, "utf8"));
    if (isObject(document) && typeof document.run_id === "string" && document.run_id !== "") {
      return document.run_id;
    }
  } catch {
    // A live marker that cannot be read is a run in progress all the same.
  }
  return null;
}

// ------------------------------------------------------------------ the episode, held

class Episode {
  constructor(recorder, suiteName, caseCompartment, setup) {
    if (caseCompartment === null || caseCompartment === undefined) {
      throw new TypeError("case");
    }
    this.recorder = recorder;
    this.suite = suiteName ? suiteName : null;
    this.caseCompartment = fromJs(caseCompartment);
    this.setup = setup === null ? null : fromJs(setup);
    this.site = recorder.on() && this.suite === null ? recorder.siteForEpisode() : null;
    this.id = null;
    this.parent = null;
    this.collector = null;
    this.answer = null;
    this.outputGiven = false;
    this.wasInterrupted = false;
    this.closed = false;
    if (!recorder.anyOn) {
      return;
    }
    this.id = randomBytes(16).toString("hex");
    this.parent = current().inside;
    const above = this.parent === null ? undefined : OPEN.get(this.parent);
    this.collector = new Collector(above !== undefined ? above.sampledOut : !recorder.episodeSampledIn());
    OPEN.set(this.id, this.collector);
    this.started = clock();
  }

  /**
   * The turn's final output: a string, or an object for a structured answer.
   * The last one given is recorded; with none, the text of the last call
   * made inside the episode.
   */
  output(result) {
    if (this.id !== null) {
      this.answer = fromJs(result);
      this.outputGiven = true;
    }
  }

  /** Says the turn ended by an error: the recording then says `interrupted`. */
  interrupted() {
    this.wasInterrupted = true;
  }

  close() {
    if (this.id === null || this.closed) {
      return;
    }
    this.closed = true;
    const elapsedMs = clock() - this.started;
    OPEN.delete(this.id);
    CLOSED.set(this.id, true);
    if (CLOSED.size > CLOSED_KEPT) {
      CLOSED.delete(CLOSED.keys().next().value);
    }
    if (this.collector.sampledOut) {
      this.recorder.countSampledOut();
      return;
    }
    this.recorder.closeEpisode(this, elapsedMs);
    if (this.parent !== null) {
      OPEN.get(this.parent)?.add(this.collector);
    }
  }
}

class Collector {
  constructor(sampledOut) {
    this.sampledOut = sampledOut;
    this.events = [];
    this.unrecorded = 0;
    this.digest = null;
  }

  add(event) {
    if (event === null) {
      this.unrecorded++;
    } else {
      this.events.push(event);
    }
  }

  calls() {
    const found = [];
    for (const event of this.events) {
      if (event instanceof Collector) {
        found.push(...event.calls());
      } else {
        found.push(event);
      }
    }
    return found;
  }

  childrenUnrecorded() {
    let own = this.unrecorded;
    for (const event of this.events) {
      if (event instanceof Collector) {
        own += event.childrenUnrecorded();
      }
    }
    return own;
  }

  /** The setup digests of the direct children, distinct and sorted. */
  digests() {
    const found = new Set();
    for (const event of this.events) {
      const digest = event instanceof Collector ? event.digest : event.digest;
      if (digest !== null && digest !== undefined) {
        found.add(digest);
      }
    }
    return [...found].sort(byCodePoint);
  }
}

// ------------------------------------------------------------------ the writer

/**
 * Files recordings under `.digline/<tenant>/recordings/n<pid>-<8 hex>/`,
 * `000001.json` and on: written to a temporary file whose name starts with a
 * dot, which no reader reads, and linked into place, which fails rather than
 * replace. Never fsynced, as digline's are not.
 */
class Writer {
  constructor(root) {
    this.root = root;
    this.places = new Map();
  }

  write(tenant, payload) {
    if (!isName(tenant)) {
      throw new TypeError(refusal(tenant));
    }
    const target = this.#next(tenant);
    const temporary = path.join(path.dirname(target), `.tmp-${randomBytes(8).toString("hex")}.json`);
    try {
      fs.writeFileSync(temporary, payload, { encoding: "utf8", flag: "wx" });
      fs.linkSync(temporary, target);
    } finally {
      fs.rmSync(temporary, { force: true });
    }
    return fs.statSync(target).size;
  }

  #next(tenant) {
    let place = this.places.get(tenant);
    if (place === undefined) {
      const store = path.join(this.root, STORE);
      layout(store, tenant);
      const directory = path.join(store, tenant, RECORDINGS, `n${process.pid}-${randomBytes(4).toString("hex")}`);
      fs.mkdirSync(path.dirname(directory), { recursive: true });
      fs.mkdirSync(directory);
      place = { directory, number: 0 };
      this.places.set(tenant, place);
    }
    place.number++;
    return path.join(place.directory, `${String(place.number).padStart(6, "0")}.json`);
  }
}

/** The layout digline makes before a tenant's first recording, so git ignores it. */
function layout(store, tenant) {
  fs.mkdirSync(path.join(store, tenant, "baselines"), { recursive: true });
  fs.mkdirSync(path.join(store, tenant, "runs"), { recursive: true });
  create(path.join(store, ".gitignore"), GITIGNORE);
  create(path.join(store, ".gitattributes"), GITATTRIBUTES);
}

function create(where, text) {
  try {
    fs.writeFileSync(where, text, { encoding: "utf8", flag: "wx" });
  } catch (exists) {
    if (exists?.code !== "EEXIST") {
      throw exists;
    }
    // Another process laid it out first, with the same text.
  }
}

// ------------------------------------------------------------------ time

/**
 * Now, in the contract's one form: UTC, to the microsecond, with the offset
 * written `+00:00` and the fraction left out when it is zero, as Python's
 * `isoformat()` writes it. Never `Z`.
 */
export function now() {
  return timestamp(Math.floor((performance.timeOrigin + performance.now()) * 1000));
}

/** A time in microseconds since the epoch, in the contract's form. */
export function timestamp(micros) {
  const whole = Math.floor(micros / 1_000_000);
  const fraction = micros - whole * 1_000_000;
  const seconds = new Date(whole * 1000).toISOString().slice(0, 19);
  return fraction === 0 ? `${seconds}+00:00` : `${seconds}.${String(fraction).padStart(6, "0")}+00:00`;
}
