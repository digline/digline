/**
 * The TOML a switch file holds: `key = value` lines, comments and blank
 * lines; booleans, integers, floats and strings; and a table's header, read
 * as a key the switch then refuses by name, as digline's reader does. An
 * array, an inline table, a date or a dotted key is refused here as not
 * valid, where digline's reader reads it and then refuses the key or its
 * type: either way the switch is not read, and the sentence differs.
 */
export function parseToml(text) {
  const found = new Map();
  let into = found;
  for (const line of text.split("\n")) {
    const stripped = withoutComment(line).trim();
    if (stripped === "") {
      continue;
    }
    if (stripped.startsWith("[") && stripped.endsWith("]") && !stripped.startsWith("[[")) {
      const name = stripped.slice(1, -1).trim();
      if (!/^[A-Za-z0-9_-]+$/.test(name) || found.has(name)) {
        throw new SyntaxError("not a table a switch reads");
      }
      into = new Map();
      found.set(name, into);
      continue;
    }
    const equals = stripped.indexOf("=");
    if (equals < 1) {
      throw new SyntaxError("not a key = value line");
    }
    let key = stripped.slice(0, equals).trim();
    if (key.length >= 2 && key.startsWith('"') && key.endsWith('"')) {
      key = tomlValue(key);
    } else if (!/^[A-Za-z0-9_-]+$/.test(key)) {
      throw new SyntaxError("not a bare key");
    }
    if (into.has(key)) {
      throw new SyntaxError("a key defined twice");
    }
    into.set(key, tomlValue(stripped.slice(equals + 1).trim()));
  }
  return found;
}

function withoutComment(line) {
  let quote = null;
  for (let i = 0; i < line.length; i++) {
    const c = line[i];
    if (quote !== null) {
      if (c === "\\" && quote === '"') {
        i++;
      } else if (c === quote) {
        quote = null;
      }
    } else if (c === '"' || c === "'") {
      quote = c;
    } else if (c === "#") {
      return line.slice(0, i);
    }
  }
  return line;
}

function tomlValue(written) {
  if (written === "true") {
    return true;
  }
  if (written === "false") {
    return false;
  }
  if (written.length >= 2 && written.startsWith("'") && written.endsWith("'")) {
    const inside = written.slice(1, -1);
    if (inside.includes("'")) {
      throw new SyntaxError("not a literal string");
    }
    return inside;
  }
  if (written.length >= 2 && written.startsWith('"') && written.endsWith('"')) {
    return parse(written);
  }
  if (written.includes("__") || written.startsWith("_") || written.endsWith("_")) {
    throw new SyntaxError("not a number");
  }
  const plain = written.replaceAll("_", "");
  if (/^[+-]?(inf|nan)$/.test(plain)) {
    return plain.endsWith("nan") ? NaN : plain.startsWith("-") ? -Infinity : Infinity;
  }
  if (/^0x[0-9A-Fa-f]+$/.test(plain) || /^0o[0-7]+$/.test(plain) || /^0b[01]+$/.test(plain)) {
    return BigInt(plain);
  }
  if (/^[+-]?(0|[1-9][0-9]*)$/.test(plain)) {
    return BigInt(plain.startsWith("+") ? plain.slice(1) : plain);
  }
  if (/^[+-]?(0|[1-9][0-9]*)(\.[0-9]+)?([eE][+-]?[0-9]+)?$/.test(plain)) {
    return Number(plain);
  }
  throw new SyntaxError("not a value a switch holds");
}

function isNumber(value) {
  return typeof value === "bigint" || typeof value === "number";
}

function asNumber(value) {
  return typeof value === "bigint" ? Number(value) : value;
}

/**
 * A switch file's text, or a `StartError` naming `where`, with the sentences
 * digline's `parse_switch` uses.
 */
export function parseSwitch(text, where, production) {
  let raw;
  try {
    raw = parseToml(text);
  } catch {
    throw new StartError(`${where} is not valid TOML`);
  }
  const unknown = [...raw.keys()].filter((key) => !SWITCH_KEYS.includes(key)).sort(byCodePoint);
  if (unknown.length > 0) {
    throw new StartError(
      `${where} has keys the recorder does not read: ${unknown.join(", ")}. It reads ${SWITCH_KEYS.join(", ")}`,
    );
  }
  const on = raw.get("on");
  if (typeof on !== "boolean") {
    throw new StartError(`${where} must say on = true or on = false`);
  }
  const sample = raw.get("sample");
  if (sample !== undefined && !(isNumber(sample) && asNumber(sample) > 0 && asNumber(sample) <= 1)) {
    throw new StartError(`${where}: sample must be a number above 0 and at most 1`);
  }
  const redact = raw.get("redact");
  if (redact !== undefined && redact !== "none") {
    const said = firstCodePoints(pythonStr(redact), 40);
    throw new StartError(
      `${where}: redact = ${pythonStringRepr(said)} is not implemented. ` +
        'This release implements redact = "none" alone (ADR 0058 §4)',
    );
  }
  const ceiling = raw.get("ceiling");
  if (ceiling !== undefined && !(typeof ceiling === "bigint" && ceiling > 0n)) {
    throw new StartError(`${where}: ceiling must be a whole number of bytes, at least 1`);
  }
  const every = raw.get("interval");
  if (every !== undefined && !(isNumber(every) && asNumber(every) > 0)) {
    throw new StartError(`${where}: interval must be a number of seconds above 0`);
  }
  const declaredProduction = raw.has("production") ? raw.get("production") : false;
  if (typeof declaredProduction !== "boolean") {
    throw new StartError(`${where}: production must be true or false`);
  }
  if ((production || declaredProduction) && on) {
    const missing = [];
    if (redact === undefined) {
      missing.push('no declared redaction (write redact = "none", the one this release implements)');
    }
    if (sample === undefined) {
      missing.push("no declared sampling (write sample = p, above 0 and at most 1)");
    }
    if (ceiling === undefined) {
      missing.push("no ceiling on the size of its recordings (write ceiling = N, in bytes)");
    }
    if (missing.length > 0) {
      throw new StartError(
        `${where} switches recording on in production with ${missing.join("; ")}. ` +
          "In production all three are declared (ADR 0058 §10)",
      );
    }
  }
  const largest = 2n ** 63n - 1n;
  return {
    on,
    sample: sample === undefined ? DEFAULT_SAMPLE : asNumber(sample),
    redact: "none",
    ceiling: ceiling === undefined ? DEFAULT_CEILING : ceiling > largest ? largest : ceiling,
    interval: every === undefined ? DEFAULT_INTERVAL : asNumber(every),
    production: declaredProduction,
    declared: new Set(raw.keys()),
  };
}

function switchedOn() {
  const value = process.env[ENVIRONMENT_VARIABLE];
  if (value === undefined || value === "" || value === "0") {
    return false;
  }
  if (value === "1") {
    return true;
  }
  throw new StartError(
    `${ENVIRONMENT_VARIABLE} is set to a value that is neither 1 (record) nor 0 or empty (do not record)`,
  );
}

