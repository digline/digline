/**
 * The suite and the episode of the calls made inside a scope, carried through
 * every `await` by Node's `AsyncLocalStorage`, as Java's recorder carries them
 * on a thread.
 */
const SCOPE = new AsyncLocalStorage();

/** The episodes open in this process, by id. */
const OPEN = new Map();

/** The episodes this process closed, most recent last, bounded. */
const CLOSED = new Map();

/** One writer per root in this process, so the process has one directory per tenant. */
const WRITERS = new Map();

function current() {
  return SCOPE.getStore() ?? { suite: null, inside: null };
}

/**
 * Runs `call` with the calls it makes, and the calls of whatever it awaits,
 * named `name`: the same name as that suite's `Suite(name=...)`. Returns what
 * `call` returns. `null` names none.
 */
export function suite(name, call) {
  return SCOPE.run({ ...current(), suite: name ? name : null }, call);
}

/**
 * Runs `call` with its calls put in the episode `id`: for work the episode's
 * own scope does not reach. `null`, which is an episode's id while the
 * recorder is off, attaches nothing.
 */
export function attach(id, call) {
  if (!id) {
    return call();
  }
  return SCOPE.run({ ...current(), inside: id }, call);
}

// ------------------------------------------------------------------ JSON values

/*
 * JSON as digline reads and writes it. JavaScript has one number type and
 * Python two, and a float's text is not an integer's (`1.0` and `1`), so a
 * value read here keeps the difference: an integer is a `bigint`, and a
 * `number` is always a float. Objects have no prototype, so that any key a
 * provider sends is a key.
 */

export function isObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function newObject() {
  return Object.create(null);
}

/** Python's string order: by code point, not by UTF-16 unit. */
export function byCodePoint(left, right) {
  let i = 0;
  let j = 0;
  while (i < left.length && j < right.length) {
    const a = left.codePointAt(i);
    const b = right.codePointAt(j);
    if (a !== b) {
      return a < b ? -1 : 1;
    }
    i += a > 0xffff ? 2 : 1;
    j += b > 0xffff ? 2 : 1;
  }
  return left.length - i - (right.length - j);
}

/**
 * A value the application built in JavaScript, read as JSON carries it: a
 * number with no fraction is an integer, as `JSON.stringify` writes it, and
 * every other number a float. A value read off the wire is never passed
 * through here: it already says which it is.
 */
export function fromJs(value) {
  if (value === null || value === undefined) {
    return null;
  }
  if (typeof value === "bigint" || typeof value === "string" || typeof value === "boolean") {
    return value;
  }
  if (typeof value === "number") {
    if (!Number.isFinite(value)) {
      throw new TypeError("NaN and the infinities are not JSON");
    }
    return Number.isInteger(value) ? BigInt(value) : value;
  }
  if (Array.isArray(value)) {
    return value.map((item) => (item === undefined ? null : fromJs(item)));
  }
  if (typeof value === "object") {
    const found = newObject();
    for (const [key, item] of Object.entries(value)) {
      if (item !== undefined) {
        found[key] = fromJs(item);
      }
    }
    return found;
  }
  throw new TypeError(`JSON cannot carry a ${typeof value}`);
}

const MODE = { COMPACT: 0, FILE: 1, DIGEST: 2 };

/** Compact, keys sorted, non-ASCII as it is: a recorded response's `input`. */
export function compact(value) {
  return write(value, MODE.COMPACT, 0);
}

/** Indented by two, keys sorted, non-ASCII as it is: a recording's file, without its newline. */
export function file(value) {
  return write(value, MODE.FILE, 0);
}

function write(value, mode, depth) {
  const out = [];
  writeInto(value, mode, depth, out);
  return out.join("");
}

function writeInto(value, mode, depth, out) {
  if (value === null || value === undefined) {
    out.push("null");
  } else if (typeof value === "string") {
    out.push(string(value, mode !== MODE.DIGEST));
  } else if (typeof value === "boolean") {
    out.push(value ? "true" : "false");
  } else if (typeof value === "bigint") {
    out.push(value.toString());
  } else if (typeof value === "number") {
    if (mode === MODE.DIGEST) {
      if (!Number.isFinite(value)) {
        throw new TypeError("NaN and the infinities are not JSON");
      }
      out.push(string(floatText(value), false));
    } else {
      out.push(pythonRepr(value));
    }
  } else if (Array.isArray(value)) {
    if (value.length === 0) {
      out.push("[]");
      return;
    }
    out.push("[");
    value.forEach((item, i) => {
      if (i > 0) {
        out.push(",");
      }
      newline(mode, depth + 1, out);
      writeInto(item, mode, depth + 1, out);
    });
    newline(mode, depth, out);
    out.push("]");
  } else if (typeof value === "object") {
    const keys = Object.keys(value).sort(byCodePoint);
    if (keys.length === 0) {
      out.push("{}");
      return;
    }
    out.push("{");
    keys.forEach((key, i) => {
      if (i > 0) {
        out.push(",");
      }
      newline(mode, depth + 1, out);
      out.push(string(key, mode !== MODE.DIGEST));
      out.push(mode === MODE.FILE ? ": " : ":");
      writeInto(value[key], mode, depth + 1, out);
    });
    newline(mode, depth, out);
    out.push("}");
  } else {
    throw new TypeError(`JSON cannot carry a ${typeof value} as it is`);
  }
}

function newline(mode, depth, out) {
  if (mode === MODE.FILE) {
    out.push("\n" + "  ".repeat(depth));
  }
}

const SHORT_ESCAPES = { '"': '\\"', "\\": "\\\\", "\n": "\\n", "\r": "\\r", "\t": "\\t", "\b": "\\b", "\f": "\\f" };

/**
 * A string as Python writes it: `"`, `\` and the control characters escaped,
 * the five with short forms by them; without `unicode`, also DEL and every
 * unit past it, as `\uXXXX`. With it, a lone surrogate is refused, as UTF-8
 * cannot carry it.
 */
function string(text, unicode) {
  let out = '"';
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    const code = text.charCodeAt(i);
    if (SHORT_ESCAPES[c] !== undefined) {
      out += SHORT_ESCAPES[c];
    } else if (code < 0x20 || (!unicode && code >= 0x7f)) {
      out += "\\u" + code.toString(16).padStart(4, "0");
    } else if (code >= 0xd800 && code <= 0xdfff) {
      const next = text.charCodeAt(i + 1);
      const paired = code <= 0xdbff && next >= 0xdc00 && next <= 0xdfff;
      if (!paired) {
        throw new TypeError("a lone surrogate is not UTF-8");
      }
      out += c + text[i + 1];
      i++;
    } else {
      out += c;
    }
  }
  return out + '"';
}

/** One JSON value, strict: NaN, the infinities and trailing text are refused. */
export function parse(text) {
  const reader = { text, at: 0 };
  const value = readValue(reader);
  space(reader);
  if (reader.at < text.length) {
    throw new SyntaxError("text after the JSON value");
  }
  return value;
}

function space(reader) {
  while (reader.at < reader.text.length && " \t\n\r".includes(reader.text[reader.at])) {
    reader.at++;
  }
}

function peek(reader) {
  if (reader.at >= reader.text.length) {
    throw new SyntaxError("the JSON ends early");
  }
  return reader.text[reader.at];
}

function expect(reader, c) {
  if (peek(reader) !== c) {
    throw new SyntaxError(`expected '${c}' at ${reader.at}`);
  }
  reader.at++;
}

function readValue(reader) {
  space(reader);
  const c = peek(reader);
  if (c === "{") {
    reader.at++;
    const found = newObject();
    space(reader);
    if (peek(reader) === "}") {
      reader.at++;
      return found;
    }
    for (;;) {
      space(reader);
      const key = readString(reader);
      space(reader);
      expect(reader, ":");
      found[key] = readValue(reader);
      space(reader);
      if (peek(reader) === ",") {
        reader.at++;
        continue;
      }
      expect(reader, "}");
      return found;
    }
  }
  if (c === "[") {
    reader.at++;
    const found = [];
    space(reader);
    if (peek(reader) === "]") {
      reader.at++;
      return found;
    }
    for (;;) {
      found.push(readValue(reader));
      space(reader);
      if (peek(reader) === ",") {
        reader.at++;
        continue;
      }
      expect(reader, "]");
      return found;
    }
  }
  if (c === '"') {
    return readString(reader);
  }
  for (const [word, value] of [["true", true], ["false", false], ["null", null]]) {
    if (reader.text.startsWith(word, reader.at)) {
      reader.at += word.length;
      return value;
    }
  }
  return readNumber(reader);
}

const NUMBER = /-?(0|[1-9][0-9]*)(\.[0-9]+)?([eE][+-]?[0-9]+)?/y;

function readNumber(reader) {
  NUMBER.lastIndex = reader.at;
  const found = NUMBER.exec(reader.text);
  if (!found || found[0] === "" || found[0] === "-") {
    throw new SyntaxError(`not a JSON number at ${reader.at}`);
  }
  const written = found[0];
  reader.at += written.length;
  if (found[2] === undefined && found[3] === undefined) {
    return BigInt(written);
  }
  const number = Number(written);
  if (!Number.isFinite(number)) {
    throw new SyntaxError("a JSON number past a double");
  }
  return number;
}

function readString(reader) {
  expect(reader, '"');
  let out = "";
  for (;;) {
    const c = peek(reader);
    reader.at++;
    if (c === '"') {
      return out;
    }
    if (c.charCodeAt(0) < 0x20) {
      throw new SyntaxError("a control character in a JSON string");
    }
    if (c !== "\\") {
      out += c;
      continue;
    }
    const escaped = peek(reader);
    reader.at++;
    const simple = { '"': '"', "\\": "\\", "/": "/", b: "\b", f: "\f", n: "\n", r: "\r", t: "\t" }[escaped];
    if (simple !== undefined) {
      out += simple;
    } else if (escaped === "u") {
      const hex = reader.text.slice(reader.at, reader.at + 4);
      if (!/^[0-9A-Fa-f]{4}$/.test(hex)) {
        throw new SyntaxError("a short \\u escape");
      }
      out += String.fromCharCode(parseInt(hex, 16));
      reader.at += 4;
    } else {
      throw new SyntaxError("an unknown escape");
    }
  }
}

// ------------------------------------------------------------------ numbers and the digest

/** The shortest digits that read back as `value`, and where the point goes. */
function shortest(value) {
  const [mantissa, exponent] = Math.abs(value).toExponential().split("e");
  const digits = mantissa.replace(".", "");
  return { digits, point: Number(exponent) + 1 };
}

/**
 * A float as the digest writes it: the shortest digits that read back as the
 * same double, positional, no trailing zeros or point; `"0"` for both zeros.
 * digline's `float_text`.
 */
export function floatText(value) {
  if (value === 0) {
    return "0";
  }
  const { digits, point } = shortest(value);
  const sign = value < 0 ? "-" : "";
  if (point <= 0) {
    return `${sign}0.${"0".repeat(-point)}${digits}`;
  }
  if (point >= digits.length) {
    return sign + digits + "0".repeat(point - digits.length);
  }
  return `${sign}${digits.slice(0, point)}.${digits.slice(point)}`;
}

/**
 * A float as Python's `repr` writes it, which is how digline writes one into
 * a file: the shortest digits that read back, positional from 1e-4 to below
 * 1e16, else with an exponent of at least two digits.
 */
export function pythonRepr(value) {
  if (!Number.isFinite(value)) {
    throw new TypeError("NaN and the infinities are not JSON");
  }
  if (value === 0) {
    return Object.is(value, -0) ? "-0.0" : "0.0";
  }
  const { digits, point } = shortest(value);
  const sign = value < 0 ? "-" : "";
  if (point <= -4 || point > 16) {
    const exponent = point - 1;
    const magnitude = String(Math.abs(exponent)).padStart(2, "0");
    const fraction = digits.length > 1 ? "." + digits.slice(1) : "";
    return `${sign}${digits[0]}${fraction}e${exponent < 0 ? "-" : "+"}${magnitude}`;
  }
  if (point <= 0) {
    return `${sign}0.${"0".repeat(-point)}${digits}`;
  }
  if (point >= digits.length) {
    return `${sign}${digits}${"0".repeat(point - digits.length)}.0`;
  }
  return `${sign}${digits.slice(0, point)}.${digits.slice(point)}`;
}

/**
 * `round(value, 6)`, as digline keeps a number in its documents: the double's
 * exact value rounded half to even at the sixth place, then read back as the
 * nearest double, as Python's `round` does.
 */
export function round(value) {
  if (!Number.isFinite(value)) {
    throw new TypeError("NaN and the infinities are not JSON");
  }
  if (value === 0) {
    return value;
  }
  const view = new DataView(new ArrayBuffer(8));
  view.setFloat64(0, value);
  const bits = view.getBigUint64(0);
  const negative = bits >> 63n === 1n;
  const biased = Number((bits >> 52n) & 0x7ffn);
  const fraction = bits & 0xfffffffffffffn;
  const mantissa = biased === 0 ? fraction : fraction | (1n << 52n);
  const exponent = (biased === 0 ? 1 : biased) - 1075;
  if (exponent >= 0) {
    return value;
  }
  const scaled = mantissa * 1_000_000n;
  const divisor = 1n << BigInt(-exponent);
  let quotient = scaled / divisor;
  const twice = (scaled % divisor) * 2n;
  if (twice > divisor || (twice === divisor && quotient % 2n === 1n)) {
    quotient += 1n;
  }
  if (quotient === 0n) {
    return negative ? -0 : 0;
  }
  return Number(`${negative ? "-" : ""}${quotient}e-6`);
}

/** A value with every float rounded as digline's `canonical` rounds it. */
export function rounded(value) {
  if (typeof value === "number") {
    return round(value);
  }
  if (Array.isArray(value)) {
    return value.map(rounded);
  }
  if (isObject(value)) {
    const found = newObject();
    for (const key of Object.keys(value)) {
      found[key] = rounded(value[key]);
    }
    return found;
  }
  return value;
}

/**
 * The setup's digest: the first 16 hexadecimal characters of the SHA-256 of
 * the setup as Python's `json.dumps` writes it, keys sorted, separators `,`
 * and `:`, non-ASCII escaped, and each float written as a string in the form
 * `floatText` gives.
 */
export function setupDigest(setup) {
  const payload = write(setup, MODE.DIGEST, 0);
  return createHash("sha256").update(payload, "utf8").digest("hex").slice(0, 16);
}

/** A string as Python's `repr` writes it, for the sentences that quote a value. */
export function pythonStringRepr(text) {
  const quote = text.includes("'") && !text.includes('"') ? '"' : "'";
  let out = quote;
  for (const c of text) {
    const code = c.codePointAt(0);
    if (c === quote || c === "\\") {
      out += "\\" + c;
    } else if (c === "\n") {
      out += "\\n";
    } else if (c === "\r") {
      out += "\\r";
    } else if (c === "\t") {
      out += "\\t";
    } else if (code < 0x20 || code === 0x7f) {
      out += "\\x" + code.toString(16).padStart(2, "0");
    } else {
      out += c;
    }
  }
  return out + quote;
}

function pythonStr(value) {
  if (typeof value === "boolean") {
    return value ? "True" : "False";
  }
  if (typeof value === "number") {
    if (Number.isNaN(value)) {
      return "nan";
    }
    if (!Number.isFinite(value)) {
      return value > 0 ? "inf" : "-inf";
    }
    return pythonRepr(value);
  }
  return String(value);
}

function firstCodePoints(text, count) {
  return [...text].slice(0, count).join("");
}

