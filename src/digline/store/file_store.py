class _MalformedLine(Exception):
    """A register line that parses into something no writer produces.

    **Deliberately not a `ValueError`.** `read_register` forgives a `ValueError`
    on the last line as a torn write, and nothing raised as this is a tear: an
    `Infinity` on the last line is a hostile line, not an interrupted one.
    """


#: Wider than any count or exit code a register holds, and far short of the
#: thousands of digits Python refuses to convert — which it refuses with a
#: `ValueError`, so a line carrying them read as torn. (0.13.0 delta-pass)
_MAX_DIGITS = 18


def _refuse_constant(name: str) -> object:
    raise _MalformedLine(f"{name} is not a value a register line can hold")


def _bounded_int(digits: str) -> int:
    length = len(digits.lstrip("-"))
    if length > _MAX_DIGITS:
        raise _MalformedLine(
            f"it holds an integer of {length} digits, which is no count"
        )
    return int(digits)


def _no_duplicate_keys(pairs: list[tuple[str, object]]) -> dict[str, object]:
    """Last-wins is `json.loads`'s default, and it let one line say both
    `accepted` and `rejected` and be read as whichever came second."""
    found: dict[str, object] = {}
    for key, value in pairs:
        if key in found:
            raise _MalformedLine(f"it has a duplicate key {key[:40]!r}")
        found[key] = value
    return found


def _parse_register_line(line: str) -> object:
    """`json.loads`, held to what a writer produces.

    A `ValueError` still means the line does not parse — which is what a torn
    tail is. Everything a hostile line can do *besides* not parsing raises
    `_MalformedLine` instead, including the `RecursionError` deep nesting drives
    the decoder into.
    """
    try:
        return json.loads(
            line,
            parse_constant=_refuse_constant,
            parse_int=_bounded_int,
            object_pairs_hook=_no_duplicate_keys,
        )
    except RecursionError:
        raise _MalformedLine("it is nested deeper than any register line") from None


def _malformed(path: Path, number: int) -> tuple[str, str]:
    """Digline's words before and after the reason a line is malformed."""
    return (
        f"{path} line {number} is malformed: ",
        ". It is a committed record, so it is named rather than repaired — "
        "restore the line from git",
    )


_MISSING = object()


def _kind(value: object) -> str:
    """What a field held, in JSON's words, and never the value itself: a refusal
    is printed, and the value is text a stranger wrote."""
    if value is _MISSING:
        return "nothing"
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "a boolean"
    if isinstance(value, int):
        return "a whole number"
    if isinstance(value, float):
        return "a decimal number"
    if isinstance(value, str):
        return "a string"
    if isinstance(value, list):
        return "a list"
    return "an object"


def _where(section: str, key: str) -> str:
    return f"{section}.{key}" if section else key


def _section(raw: Mapping[str, object], name: str) -> Mapping[str, object]:
    found = raw.get(name, _MISSING)
    if not isinstance(found, dict):
        raise _MalformedLine(f"{name} must be an object, got {_kind(found)}")
    return cast(Mapping[str, object], found)


def _text(
    fields: Mapping[str, object], key: str, section: str = "", *, optional: bool = False
) -> str:
    value = fields.get(key, _MISSING)
    if optional and (value is _MISSING or value is None):
        return ""
    if not isinstance(value, str):
        raise _MalformedLine(
            f"{_where(section, key)} must be a string, got {_kind(value)}"
        )
    return value


def _flag(fields: Mapping[str, object], key: str, section: str) -> bool:
    value = fields.get(key, _MISSING)
    if not isinstance(value, bool):
        raise _MalformedLine(
            f"{_where(section, key)} must be true or false, got {_kind(value)}"
        )
    return value


def _whole(fields: Mapping[str, object], key: str, section: str = "") -> int:
    value = fields.get(key, _MISSING)
    # `bool` is an `int` in Python, and `true` is not a count.
    if isinstance(value, bool) or not isinstance(value, int):
        raise _MalformedLine(
            f"{_where(section, key)} must be a whole number, got {_kind(value)}"
        )
    return value


def _entry_from_dict(raw: Mapping[str, object]) -> RegisterEntry:
    """A line held to the types `_entry_to_dict` writes: refused, never coerced.

    `bool("false")` is `True` and `int(2.9)` is `2`, so a reader that converts
    reads a different record than the bytes hold — which is the one thing a
    committed record must never do, and what ADR 0021 §5 already said: a line
    this digline cannot read is refused by name. (0.13.0 delta-pass)
    """
    run = _section(raw, "run")
    baseline = _section(raw, "baseline")
    outcome = _section(raw, "outcome")
    disposition = raw.get("disposition", _MISSING)
    if disposition not in DISPOSITIONS:
        # A string is named as one and not quoted: the refusal is printed, and
        # the value is text a stranger wrote.
        got = "another string" if isinstance(disposition, str) else _kind(disposition)
        raise _MalformedLine(
            f"disposition must be one of {', '.join(DISPOSITIONS)}, got {got}"
        )
    return RegisterEntry(
        recorded_at=_text(raw, "recorded_at"),
        digline_version=_text(raw, "digline_version", optional=True),
        disposition=disposition,
        run_key=_text(run, "key", "run"),
        run_created_at=_text(run, "created_at", "run"),
        run_config_hash=_text(run, "config_hash", "run"),
        run_environment=_text(run, "environment", "run"),
        run_digline_version=_text(run, "digline_version", "run", optional=True),
        run_rejudged=_flag(run, "rejudged", "run"),
        baseline_key=_text(baseline, "key", "baseline"),
        baseline_config_hash=_text(baseline, "config_hash", "baseline"),
        baseline_promoted_at=_text(baseline, "promoted_at", "baseline", optional=True),
        outcome=RecordedOutcome(
            **{name: _whole(outcome, name, "outcome") for name in _OUTCOME_FIELDS},
            **{name: _flag(outcome, name, "outcome") for name in _OUTCOME_FLAGS},
        ),
        exit_code=_whole(raw, "exit_code"),
    )


#: Where journals live: a dot-directory under the suite's runs, so the generated
#: `.gitignore` already covers it (`*/runs/` ignores the directory and
#: everything beneath it) and every `*.json` listing in this module steps over it.
#: A journal is not a document: nothing lists it, compares it, migrates it or
#: renders it. (ADR 0017 §2)
PENDING_DIRNAME = ".pending"

_LEG_RE = re.compile(r"^(?P<key>.+)\.(?P<leg>[0-9]+)$")


def journal_key(header: JournalHeader) -> str:
    """The key a journal — and therefore the run it becomes — is named after.

    `key_of` again, over the header instead of the run — the same rule
    `write_run` is held to — and that is the point: a resumed run keeps the
    original `created_at` (ADR 0017 §8), so it is written to exactly the file
    the killed run was always going to write.
    """
    return key_of(header.created_at, header.config_hash)


def _header_to_dict(header: JournalHeader) -> dict[str, object]:
    return {
        "kind": "header",
        "journal_version": header.journal_version,
        "leg": header.leg,
        "tenant": header.tenant,
        "environment": header.environment,
        "suite": header.suite,
        "config_hash": header.config_hash,
        "cases_digest": header.cases_digest,
        "created_at": header.created_at,
        "started_at": header.started_at,
        "digline_version": header.digline_version,
        "record_responses": header.record_responses,
        "git_commit": header.git_commit,
        "artifacts": dict(sorted(header.artifacts.items())),
        "pinned": sorted(header.pinned),
        "target_config": config_to_dict(header.target_config),
        "judge_config": config_to_dict(header.judge_config),
    }


def _header_from_dict(raw: Mapping[str, object]) -> JournalHeader:
    commit = raw.get("git_commit")
    return JournalHeader(
        tenant=str(raw["tenant"]),
        environment=str(raw["environment"]),
        suite=str(raw["suite"]),
        config_hash=str(raw["config_hash"]),
        cases_digest=str(raw["cases_digest"]),
        created_at=str(raw["created_at"]),
        started_at=str(raw["started_at"]),
        digline_version=str(raw["digline_version"]),
        # Declared, not converted: `bool("false")` is true, and a resumed run
        # would have recorded answers the run it continues did not. (#379)
        record_responses=declared_boolean(raw, "record_responses", "journal header"),
        git_commit=None if commit is None else str(commit),
        pinned=tuple(
            sorted(
                str(path) for path in cast("Sequence[object]", raw.get("pinned") or ())
            )
        ),
        artifacts={
            str(path): str(sha)
            for path, sha in cast(
                Mapping[str, object], raw.get("artifacts") or {}
            ).items()
        },
        target_config=config_from_dict(
            cast(Mapping[str, object], raw.get("target_config") or {}), "target_config"
        ),
        judge_config=config_from_dict(
            cast(Mapping[str, object], raw.get("judge_config") or {}), "judge_config"
        ),
        # Declared, not converted: `int()` read "3" and 3.9 as format 3. (#350)
        journal_version=declared_integer(raw, "journal_version"),
        leg=declared_integer(raw, "leg"),
    )


def _line(payload: Mapping[str, object]) -> str:
    return json.dumps(payload, sort_keys=True, separators=(",", ":")) + "\n"


class FileJournal:
    """One leg of a run, appended to as the run goes.

    Opened with `O_CREAT|O_EXCL`, which is the entire concurrency story: a
    second process resuming the same run finds the leg taken and is refused by
    name. No lock file — the process this exists for is one that was killed, and
    a lock it could not release would block the rescue. (ADR 0017 §5)
    """

    def __init__(self, path: Path, header: JournalHeader) -> None:
        self._path = path
        self._header = header
        try:
            descriptor = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
        except FileExistsError as exc:
            raise JournalBusyError(
                f"leg {header.leg} of run {journal_key(header)} is already being "
                f"written at {path}: another digline is resuming this run. Wait "
                "for it, or look at what it is doing before starting a second "
                "one — two processes resuming one run would both call the cases "
                "neither has finished"
            ) from exc
        self._handle = os.fdopen(descriptor, "w", encoding="utf-8")
        # Distinct from `SystemConfig()`, which is a legitimate observation:
        # *nothing observed yet* must not compare equal to *observed nothing*,
        # or the first case of a run that declares no configuration would write
        # an observation record saying so.
        self._seen: tuple[SystemConfig, SystemConfig] | None = None
        self._write(_header_to_dict(header))

    @property
    def key(self) -> str:
        return journal_key(self._header)

    @property
    def leg(self) -> int:
        return self._header.leg

    @property
    def path(self) -> Path:
        return self._path

    def _write(self, payload: Mapping[str, object]) -> None:
        """One record, on disk before this returns.

        `flush` would survive a kill; `fsync` is here because the incident that
        produced this feature was memory pressure on a whole machine, and the
        syscall costs microseconds against a case that cost a network call. The
        one thing this file may not do is be fast and empty. (ADR 0017 §3)
        """
        self._handle.write(_line(payload))
        self._handle.flush()
        os.fsync(self._handle.fileno())

    def append(self, progress: CaseProgress) -> None:
        observed = (progress.observed_target, progress.observed_judge)
        if observed != self._seen:
            # Written when it changes, which in an uninterrupted run means once:
            # after the first case that revealed an identity. It is what a
            # resume seeds the target from, so an alias that rolls across the
            # seam raises instead of being averaged. (ADR 0017 §7)
            self._seen = observed
            self._write(
                {
                    "kind": "observed",
                    "target_config": config_to_dict(progress.observed_target),
                    "judge_config": config_to_dict(progress.observed_judge),
                }
            )
        self._write(
            {
                "kind": "case",
                "cause": progress.cause,
                "case": case_to_dict(progress.result, redacted=False),
                # What this case's calls consumed, written whatever the suite
                # records. It is the journal's own fact about work already paid
                # for, not a recording of the answer: a resume that could not
                # add up the legs it did not run would write a document whose
                # bill omits them, and omit them in silence. (ADR 0025 §11)
                "usage": totals_to_dict(progress.usage),
            }
        )

    def complete(self) -> None:
        """The run is written; every leg goes."""
        self._handle.close()
        directory = self._path.parent
        # `glob`, not `_listed`, and on purpose: the run file is already
        # written, so a refusal here would report a finished run as failed.
        # A leg this cannot see stays on disk, and `pending` names it as
        # finished and removes it once the directory can be read. (#365)
        for leg in sorted(directory.glob(f"{glob.escape(self.key)}.*.jsonl")):
            leg.unlink(missing_ok=True)
        # Only when nothing else is pending: another run of the same suite may
        # be journalling right now.
        with suppress(OSError):
            directory.rmdir()
